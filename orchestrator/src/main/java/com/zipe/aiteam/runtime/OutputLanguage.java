package com.zipe.aiteam.runtime;

/**
 * 所有 agent 共用的輸出語言規則。
 *
 * 系統對人的介面（Slack 訊息、按鈕、狀態說明）全是台灣繁體中文，agent 產出的文字也要一致；
 * 模型容易混入簡體字或中國大陸用語，所以每條呼叫路徑（階段、對話、諮詢、rules 提案、legacy 階段、
 * 錯誤白話說明）都附上同一段規則，不依賴各角色 prompt 或團隊配置自行記得寫。
 * 規則以原則描述，例子只示範方向，不是比對清單。
 */
public final class OutputLanguage {

    public static final String RULE = "\n\n【輸出語言（所有角色一律適用）】"
            + "\n- 給人看的文字（回覆、摘要、報告、提問、交接說明，以及新寫的中文文件與註解）一律使用台灣口語的繁體中文。"
            + "\n- 字形只用繁體，不得出現任何簡體字；用詞採台灣說法，不用中國大陸用語"
            + "（例如寫程式碼、預設、資料庫、伺服器、介面、品質，而不是代码、默认、数据库、服务器、接口、质量）。"
            + "\n- 技術術語、程式碼識別字、指令，以及引用的原文（程式碼、日誌、錯誤訊息、檔名、使用者原話）維持原樣，不翻譯也不改字。"
            + "\n- 目標專案文件明定某類內容用其他語言（例如英文 commit 或註解）時，該類內容依專案規定。"
            + "\n- 送出前自行檢查一次，發現簡體字或大陸用語就改成台灣繁體再輸出。";

    private OutputLanguage() { }
}
